package util;

public class Fala {

    private final String personagem;
    private final String texto;

    public Fala(String personagem, String texto) {
        this.personagem = personagem;
        this.texto = texto;
    }

    public String getPersonagem() {
        return personagem;
    }

    public String getTexto() {
        return texto;
    }

}


